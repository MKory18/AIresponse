/** هل تشتغل الجولة لحالها؟ أول مرة بس، وبالرئيسية بس (مش بنص شغل بصفحة تانية). */
export function shouldAutoStartTour(pathname: string, seenRaw: string | null): boolean {
  return pathname === "/dashboard" && seenRaw !== "1";
}
