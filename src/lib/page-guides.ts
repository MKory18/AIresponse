/** شرح الصفحة الي بتخدم هالمسار (أطول رابط مطابق، مع الأسماء المستعارة). */
export function guideForPath(pathname: string): { href: string; guide: PageGuide } | null {
  const hit = pageForPath(pathname, NAV_GROUPS);
  if (!hit) return null;
  const guide = PAGE_GUIDES[hit.page.href];
  return guide ? { href: hit.page.href, guide } : null;
}

/** قائمة الصفحات المزارة — أقصى طول حتى ما تكبر لحد غير معقول بالتخزين. */
const SEEN_MAX = 200;

/**
 * أول زيارة بس: بتقرر إذا الشرح يتفتح لحاله، وبتحدّث قائمة «شفته من قبل».
 *
 * - الصفحة مش بالقائمة ← أول زيارة ← بتنضاف.
 * - `canAutoOpen = false` (صندوق الوارد، شاشة كاملة): بتنعلّم مزارة بس ما بتفتح.
 * - JSON تالف أو مش مصفوفة ← بنبدأ من فاضي (التخزين المحلي ممكن يتخرّب).
 */
export function visitGuide(
  seenRaw: string | null,
  href: string,
  canAutoOpen: boolean
): { open: boolean; seenRaw: string } {
  let seen: string[] = [];
  try {
    const parsed: unknown = seenRaw ? JSON.parse(seenRaw) : [];
    if (Array.isArray(parsed)) seen = parsed.filter((x): x is string => typeof x === "string");
  } catch {
    seen = [];
  }
  if (seen.includes(href)) return { open: false, seenRaw: JSON.stringify(seen) };
  seen.push(href);
  if (seen.length > SEEN_MAX) seen = seen.slice(seen.length - SEEN_MAX);
  return { open: canAutoOpen, seenRaw: JSON.stringify(seen) };
}
